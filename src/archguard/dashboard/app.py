
"""
ArchGuard AI — Interactive Software Architecture Dashboard.

Features:
    - FastAPI backend integration
    - Python project architecture analysis
    - Architecture summary metrics
    - Layer-aware dependency visualization
    - Interactive architectural layer filtering
    - Architectural findings and severity filtering
    - Python module explorer
    - JSON report export
    - Professional PDF architecture report export

The dashboard uses separate visualization and reporting
components to maintain separation of responsibilities.

The dependency listing intentionally avoids st.dataframe()
because Windows Application Control may block the native
PyArrow DLL required by some Streamlit dataframe operations.
"""

import json
import os
import re

import httpx
import streamlit as st

from archguard.adapters.pdf_report import PDFReportGenerator
from archguard.dashboard.visualization import (
    LAYER_ORDER,
    create_dependency_figure,
)


# ============================================================
# Configuration
# ============================================================

API_URL = os.getenv(
    "ARCHGUARD_API_URL",
    "http://127.0.0.1:8000",
).rstrip("/")

st.set_page_config(
    page_title="ArchGuard AI",
    page_icon="🛡️",
    layout="wide",
    initial_sidebar_state="expanded",
)


# ============================================================
# FastAPI Backend Communication
# ============================================================

def check_api_health() -> bool:
    """
    Verify whether the FastAPI backend is available.

    Returns True only when the health endpoint
    responds successfully.
    """

    try:
        response = httpx.get(
            f"{API_URL}/health",
            timeout=5.0,
        )

        response.raise_for_status()

        return (
            response.json().get("status") == "healthy"
        )

    except (httpx.HTTPError, ValueError):
        return False


def analyze_project(project_path: str) -> dict:
    """
    Request architecture analysis from FastAPI.

    Returns a dictionary containing:
        - project_name
        - summary
        - modules
        - dependencies
        - findings
    """

    with httpx.Client(timeout=60.0) as client:
        response = client.post(
            f"{API_URL}/analyze",
            json={
                "project_path": project_path,
            },
        )

        response.raise_for_status()

        return response.json()


# ============================================================
# Architecture Summary Metrics
# ============================================================

def display_summary(report: dict) -> None:
    """Display architecture analysis metrics."""

    summary = report.get("summary", {})

    col1, col2, col3 = st.columns(3)

    col1.metric(
        label="Python Modules",
        value=summary.get("module_count", 0),
    )

    col2.metric(
        label="Internal Dependencies",
        value=summary.get("dependency_count", 0),
    )

    col3.metric(
        label="Architecture Findings",
        value=summary.get("finding_count", 0),
    )


# ============================================================
# Architecture Findings
# ============================================================

def display_findings(report: dict) -> None:
    """
    Display architectural findings with severity filters.

    Findings are generated by the architecture rule engine.
    """

    findings = report.get("findings", [])

    if not findings:
        st.success(
            "No issues detected by the configured "
            "architecture rules."
        )

        st.caption(
            "This does not guarantee the entire software "
            "architecture is free of design problems."
        )

        return

    severity_filter = st.multiselect(
        "Filter by severity",
        options=[
            "error",
            "warning",
            "info",
        ],
        default=[
            "error",
            "warning",
            "info",
        ],
    )

    filtered_findings = [
        finding
        for finding in findings
        if finding.get("severity") in severity_filter
    ]

    if not filtered_findings:
        st.info(
            "No architectural findings match "
            "the selected severity filters."
        )

        return

    for index, finding in enumerate(
        filtered_findings,
        start=1,
    ):
        severity = finding.get(
            "severity",
            "info",
        ).upper()

        rule_id = finding.get(
            "rule_id",
            "UNKNOWN_RULE",
        )

        with st.expander(
            f"{index}. {severity} — {rule_id}"
        ):
            st.write(
                "**Module:**",
                finding.get("module", "Unknown"),
            )

            st.write(
                "**Severity:**",
                severity,
            )

            st.write(
                "**Description:**",
                finding.get(
                    "message",
                    "No description available.",
                ),
            )


# ============================================================
# Python Module Explorer
# ============================================================

def display_modules(report: dict) -> None:
    """Explore extracted Python modules and their metadata."""

    modules = report.get("modules", [])

    if not modules:
        st.info(
            "No Python modules were discovered."
        )

        return

    selected_name = st.selectbox(
        "Select a Python module",
        options=[
            module["name"]
            for module in modules
        ],
    )

    selected_module = next(
        module
        for module in modules
        if module["name"] == selected_name
    )

    st.write(
        "**File path:**",
        selected_module.get("path", ""),
    )

    # --------------------------------------------------------
    # Display imports
    # --------------------------------------------------------

    st.subheader("Imports")

    imports = selected_module.get(
        "imports",
        [],
    )

    if imports:
        for imported in imports:
            st.code(
                imported,
                language="python",
            )
    else:
        st.info(
            "No imports detected."
        )

    # --------------------------------------------------------
    # Display functions
    # --------------------------------------------------------

    st.subheader("Functions")

    functions = selected_module.get(
        "functions",
        [],
    )

    if functions:
        for function in functions:
            st.code(
                function,
                language="python",
            )
    else:
        st.info(
            "No module-level functions detected."
        )

    # --------------------------------------------------------
    # Display classes
    # --------------------------------------------------------

    st.subheader("Classes")

    classes = selected_module.get(
        "classes",
        [],
    )

    if not classes:
        st.info(
            "No classes detected in this module."
        )

        return

    for cls in classes:
        with st.expander(
            cls.get("name", "Unnamed Class")
        ):
            st.write(
                "**Class name:**",
                cls.get("name", ""),
            )

            st.write(
                "**Methods:**",
            )

            methods = cls.get(
                "methods",
                [],
            )

            if methods:
                for method in methods:
                    st.code(
                        method,
                        language="python",
                    )
            else:
                st.write(
                    "No methods detected."
                )

            st.write(
                "**Base classes:**",
            )

            bases = cls.get(
                "bases",
                [],
            )

            if bases:
                for base in bases:
                    st.code(
                        base,
                        language="python",
                    )
            else:
                st.write(
                    "No inheritance detected."
                )


# ============================================================
# Internal Dependency Listing
# ============================================================

def display_dependencies(report: dict) -> None:
    """
    Display internal module dependencies without st.dataframe().

    This avoids the PyArrow conversion path that
    previously failed under Windows Application Control.
    """

    dependencies = report.get(
        "dependencies",
        [],
    )

    st.subheader(
        "Internal Dependencies"
    )

    if not dependencies:
        st.info(
            "No internal dependencies were detected."
        )

        return

    st.caption(
        f"{len(dependencies)} internal module "
        "dependencies identified."
    )

    for index, dependency in enumerate(
        dependencies,
        start=1,
    ):
        source = dependency.get(
            "source",
            "Unknown",
        )

        target = dependency.get(
            "target",
            "Unknown",
        )

        st.markdown(
            f"**{index}.** `{source}` → `{target}`"
        )


# ============================================================
# JSON and PDF Report Export
# ============================================================

def display_report_export(report: dict) -> None:
    """Provide downloadable JSON and PDF architecture reports."""

    st.subheader("Export Architecture Report")

    st.write(
        "Download the complete architecture assessment, "
        "including module metrics, dependencies, "
        "architectural findings, and recommendations."
    )

    project_name = report.get(
        "project_name",
        "project",
    )

    # Sanitize the project name for download filenames.
    safe_name = re.sub(
        r"[^A-Za-z0-9_-]",
        "_",
        project_name,
    ) or "project"

    # --------------------------------------------------------
    # Prepare JSON report
    # --------------------------------------------------------

    report_json = json.dumps(
        report,
        indent=2,
        ensure_ascii=False,
    )

    # --------------------------------------------------------
    # Prepare PDF report
    # --------------------------------------------------------

    try:
        generator = PDFReportGenerator()
        pdf_bytes = generator.generate(report)

    except (ValueError, OSError) as exc:
        pdf_bytes = None

        st.error(
            f"Unable to generate PDF report: {exc}"
        )

    # --------------------------------------------------------
    # Download buttons
    # --------------------------------------------------------

    col1, col2 = st.columns(2)

    with col1:
        st.download_button(
            label="Download JSON Report",
            data=report_json,
            file_name=(
                f"archguard_{safe_name}_report.json"
            ),
            mime="application/json",
            use_container_width=True,
        )

    with col2:
        if pdf_bytes is not None:
            st.download_button(
                label="Download PDF Report",
                data=pdf_bytes,
                file_name=(
                    f"archguard_{safe_name}_report.pdf"
                ),
                mime="application/pdf",
                use_container_width=True,
            )


# ============================================================
# Main Dashboard
# ============================================================

def main() -> None:
    """Render the ArchGuard AI dashboard."""

    st.title(
        "🛡️ ArchGuard AI"
    )

    st.caption(
        "Intelligent Software Architecture Analysis System"
    )

    # --------------------------------------------------------
    # Sidebar: Backend Connection
    # --------------------------------------------------------

    st.sidebar.header(
        "Project Analysis"
    )

    st.sidebar.caption(
        "Analyze a Python directory within "
        "the configured API workspace."
    )

    backend_available = check_api_health()

    if backend_available:
        st.sidebar.success(
            "Backend connected"
        )
    else:
        st.sidebar.error(
            "Backend unavailable"
        )

        st.warning(
            f"Start FastAPI on {API_URL} "
            "before analyzing a project."
        )

        st.stop()

    # --------------------------------------------------------
    # Sidebar: Project Selection
    # --------------------------------------------------------

    project_path = st.sidebar.text_input(
        "Project directory",
        value="src",
        help=(
            "Enter a relative directory inside the "
            "API workspace, such as 'src'."
        ),
    )

    analyze_clicked = st.sidebar.button(
        "Analyze Project",
        type="primary",
        use_container_width=True,
    )

    # --------------------------------------------------------
    # Execute Architecture Analysis
    # --------------------------------------------------------

    if analyze_clicked:
        if not project_path.strip():
            st.error(
                "Please enter a project directory."
            )

        else:
            try:
                with st.spinner(
                    "Analyzing software architecture..."
                ):
                    report = analyze_project(
                        project_path.strip()
                    )

                st.session_state[
                    "analysis_report"
                ] = report

                st.success(
                    "Project analysis completed successfully."
                )

            except httpx.HTTPStatusError as exc:
                st.error(
                    "Architecture analysis failed. "
                    f"HTTP {exc.response.status_code}: "
                    f"{exc.response.text}"
                )

            except httpx.RequestError as exc:
                st.error(
                    f"Unable to connect to FastAPI: {exc}"
                )

            except ValueError as exc:
                st.error(
                    f"Invalid backend response: {exc}"
                )

    # --------------------------------------------------------
    # Display Analysis Results
    # --------------------------------------------------------

    report = st.session_state.get(
        "analysis_report"
    )

    if report is None:
        st.info(
            "Select a project directory and click "
            "'Analyze Project' to begin."
        )

        return

    st.divider()

    st.subheader(
        "Architecture Report: "
        f"{report.get('project_name', 'Unknown')}"
    )

    display_summary(report)

    st.divider()

    # --------------------------------------------------------
    # Dashboard Tabs
    # --------------------------------------------------------

    tab1, tab2, tab3, tab4 = st.tabs(
        [
            "Dependency Graph",
            "Architectural Findings",
            "Module Explorer",
            "Export Report",
        ]
    )

    # --------------------------------------------------------
    # Tab 1: Layer-Aware Dependency Graph
    # --------------------------------------------------------

    with tab1:
        st.subheader(
            "Architecture Visualization"
        )

        st.caption(
            "Explore module dependencies by architectural "
            "layer. Arrows point from importing modules "
            "to their dependencies."
        )

        selected_layers = st.multiselect(
            "Visible architecture layers",
            options=list(LAYER_ORDER),
            default=list(LAYER_ORDER),
            help=(
                "Select the architectural layers "
                "to display in the dependency graph."
            ),
        )

        figure = create_dependency_figure(
            modules=report.get(
                "modules",
                [],
            ),
            dependencies=report.get(
                "dependencies",
                [],
            ),
            visible_layers=selected_layers,
        )

        st.plotly_chart(
            figure,
            use_container_width=True,
        )

        st.caption(
            "Hover over a node to see its full module name, "
            "architectural layer, and dependency counts."
        )

        display_dependencies(report)

    # --------------------------------------------------------
    # Tab 2: Architectural Findings
    # --------------------------------------------------------

    with tab2:
        display_findings(report)

    # --------------------------------------------------------
    # Tab 3: Python Module Explorer
    # --------------------------------------------------------

    with tab3:
        display_modules(report)

    # --------------------------------------------------------
    # Tab 4: PDF and JSON Report Export
    # --------------------------------------------------------

    with tab4:
        display_report_export(report)


# ============================================================
# Application Entry Point
# ============================================================

if __name__ == "__main__":
    main()
