
"""
ArchGuard AI — FastAPI REST Backend.

Features:
    - Application homepage
    - Health monitoring
    - Python project architecture analysis
    - Circular dependency detection
    - High coupling detection
    - Hexagonal Architecture boundary validation
    - Optional Qwen AI architecture explanations
    - Workspace path validation
    - Interactive OpenAPI documentation

The deterministic architecture rule engine remains
the authoritative source of architectural findings.

Qwen provides optional explanations only.
"""

from pathlib import Path

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from archguard.adapters.ollama_ai import (
    AIExplanationError,
    OllamaArchitectureAssistant,
)
from archguard.application.architecture_evaluator import (
    ArchitectureEvaluator,
)
from archguard.bootstrap import create_project_scanner


# ============================================================
# Request Models
# ============================================================

class AnalysisRequest(BaseModel):
    """
    Request model for Python project architecture analysis.

    The client provides a project path, not architecture
    findings. Findings are generated by the rule engine.
    """

    project_path: str = Field(
        min_length=1,
        description=(
            "Path to a Python project directory within "
            "the configured workspace."
        ),
        examples=["src"],
    )


# ============================================================
# FastAPI Application Factory
# ============================================================

def create_app(
    allowed_root: str | Path = ".",
) -> FastAPI:
    """
    Create and configure the ArchGuard AI REST API.

    The analyzed project must be inside the allowed workspace.

    Dependencies:
        ProjectScanner -> ArchitectureEvaluator
        ArchitectureEvaluator -> Domain Rules
        OllamaArchitectureAssistant -> Local Ollama

    Qwen is optional. The deterministic analyzer continues
    functioning when the AI service is unavailable.
    """

    workspace = Path(allowed_root).resolve()

    app = FastAPI(
        title="ArchGuard AI",
        description=(
            "An Intelligent Software Architecture Analysis "
            "System that analyzes Python projects, extracts "
            "structural metadata, detects module dependencies, "
            "evaluates architectural design rules, and optionally "
            "explains verified findings using a local AI model."
        ),
        version="0.1.0",
    )

    # ========================================================
    # Homepage Endpoint
    # ========================================================

    @app.get(
        "/",
        tags=["Application"],
        summary="ArchGuard AI Homepage",
    )
    def home():
        """Return application information and API endpoints."""

        return {
            "application": "ArchGuard AI",
            "description": (
                "Intelligent Software Architecture Analysis System"
            ),
            "version": "0.1.0",
            "status": "running",
            "endpoints": {
                "home": "/",
                "health": "/health",
                "analyze": "/analyze",
                "explain": "/analyze/explain",
                "documentation": "/docs",
                "openapi": "/openapi.json",
            },
        }

    # ========================================================
    # Health Check Endpoint
    # ========================================================

    @app.get(
        "/health",
        tags=["Application"],
        summary="Check API Health",
    )
    def health():
        """Check whether the FastAPI backend is running."""

        return {
            "status": "healthy",
            "application": "ArchGuard AI",
        }

    # ========================================================
    # Architecture Analysis Endpoint
    # ========================================================

    @app.post(
        "/analyze",
        tags=["Architecture Analysis"],
        summary="Analyze a Python Project",
    )
    def analyze(request: AnalysisRequest):
        """
        Analyze a Python project's software architecture.

        The analysis includes:
            - Python modules
            - Classes and inheritance
            - Methods and functions
            - Absolute and relative imports
            - Internal module dependencies
            - Circular dependency detection
            - Coupling analysis
            - Layer boundary violations

        Returns a structured JSON architecture report.
        """

        # ----------------------------------------------------
        # Resolve requested project directory
        # ----------------------------------------------------

        requested = Path(
            request.project_path
        )

        if requested.is_absolute():
            project_root = requested.resolve()
        else:
            project_root = (
                workspace / requested
            ).resolve()

        # ----------------------------------------------------
        # Enforce workspace boundary
        # ----------------------------------------------------

        if not project_root.is_relative_to(workspace):
            raise HTTPException(
                status_code=403,
                detail=(
                    "Project is outside the allowed workspace."
                ),
            )

        if not project_root.is_dir():
            raise HTTPException(
                status_code=404,
                detail="Project directory not found.",
            )

        # ----------------------------------------------------
        # Execute deterministic architecture analysis
        # ----------------------------------------------------

        try:
            scanner = create_project_scanner()

            modules = scanner.scan(
                project_root
            )

            evaluator = ArchitectureEvaluator()

            report = evaluator.evaluate(
                project_name=project_root.name,
                modules=modules,
            )

        except (
            SyntaxError,
            UnicodeError,
            ValueError,
        ) as exc:
            raise HTTPException(
                status_code=422,
                detail=(
                    f"Unable to analyze project: {exc}"
                ),
            ) from exc

        except OSError as exc:
            raise HTTPException(
                status_code=422,
                detail=(
                    f"Unable to read project: {exc}"
                ),
            ) from exc

        # ----------------------------------------------------
        # Structured JSON architecture report
        # ----------------------------------------------------

        return {
            "project_name": report.project_name,

            "summary": {
                "module_count": report.module_count,
                "dependency_count": len(
                    report.dependencies
                ),
                "finding_count": report.finding_count,
            },

            "modules": [
                {
                    "name": module.name,
                    "path": module.path,

                    "classes": [
                        {
                            "name": cls.name,
                            "methods": list(
                                cls.methods
                            ),
                            "bases": list(
                                cls.bases
                            ),
                        }
                        for cls in module.classes
                    ],

                    "functions": list(
                        module.functions
                    ),

                    "imports": list(
                        module.imports
                    ),
                }
                for module in report.modules
            ],

            "dependencies": [
                {
                    "source": dependency.source,
                    "target": dependency.target,
                }
                for dependency in report.dependencies
            ],

            "findings": [
                {
                    "rule_id": finding.rule_id,
                    "severity": finding.severity.value,
                    "message": finding.message,
                    "module": finding.module,
                }
                for finding in report.findings
            ],
        }

    # ========================================================
    # Optional AI Architecture Explanation Endpoint
    # ========================================================

    @app.post(
        "/analyze/explain",
        tags=["AI Architecture Assistant"],
        summary="Explain Verified Architecture Findings",
    )
    def explain_architecture(request: AnalysisRequest):
        """
        Analyze a Python project and optionally explain
        architectural findings using a local Qwen model.

        Security and reliability:
            - The client provides only a project path.
            - Project paths are restricted to the workspace.
            - Findings originate from the deterministic engine.
            - AI cannot modify verified findings.
            - Clean projects do not trigger Ollama requests.
            - AI failures do not affect normal analysis.
        """

        # ----------------------------------------------------
        # Run the existing deterministic analysis
        # ----------------------------------------------------

        report = analyze(
            request
        )

        findings = report.get(
            "findings",
            [],
        )

        project_name = report[
            "project_name"
        ]

        # ----------------------------------------------------
        # Initialize the optional AI adapter
        # ----------------------------------------------------

        assistant = OllamaArchitectureAssistant()

        # ----------------------------------------------------
        # No findings: avoid unnecessary AI calls
        # ----------------------------------------------------

        if not findings:

            result = assistant.explain(
                project_name=project_name,
                findings=[],
            )

            return {
                "project_name": project_name,
                "analysis_summary": report["summary"],
                "verified_findings": [],
                "ai": result,
            }

        # ----------------------------------------------------
        # Enforce maximum number of AI findings
        # ----------------------------------------------------

        if len(findings) > assistant.MAX_FINDINGS:
            raise HTTPException(
                status_code=422,
                detail=(
                    "This project has more architectural "
                    "findings than the AI explanation limit. "
                    f"Maximum: {assistant.MAX_FINDINGS}."
                ),
            )

        # ----------------------------------------------------
        # Request AI explanation
        # ----------------------------------------------------

        try:
            result = assistant.explain(
                project_name=project_name,
                findings=findings,
            )

        except AIExplanationError as exc:
            raise HTTPException(
                status_code=503,
                detail=(
                    "Local AI explanation service unavailable: "
                    f"{exc}"
                ),
            ) from exc

        except ValueError as exc:
            raise HTTPException(
                status_code=422,
                detail=str(exc),
            ) from exc

        # ----------------------------------------------------
        # Return verified findings and AI explanation separately
        # ----------------------------------------------------

        return {
            "project_name": project_name,

            "analysis_summary": report[
                "summary"
            ],

            "verified_findings": findings,

            "ai": result,
        }

    return app


# ============================================================
# Application Entry Point
# ============================================================

app = create_app()
